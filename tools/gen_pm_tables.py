"""Pitch tables for the physical-modeling engine at 44100 Hz (A4 = 440)."""
import math
from pathlib import Path

FS = 44100
OUT = Path(__file__).resolve().parents[1] / "dsp" / "pm_tables.h"


def main() -> None:
    incs = []
    dels = []
    for n in range(128):
        f = 440.0 * 2 ** ((n - 69) / 12)
        inc = int(round(f * (2**32) / FS)) & 0xFFFFFFFF
        samples = FS / f
        if samples > 1500:
            samples = 1500
        if samples < 4:
            samples = 4
        dels.append(int(round(samples * 65536)))
        incs.append(inc)

    def rows(vals, per, fmt):
        lines = []
        for i in range(0, len(vals), per):
            chunk = ", ".join(fmt.format(v) for v in vals[i : i + per])
            lines.append("    " + chunk + ",")
        return "\n".join(lines)

    text = (
        "/* Generated by tools/gen_pm_tables.py — 44100 Hz, A4 = 440 Hz. Do not edit by hand.\n"
        " * PM_INC: phase increment, one cycle across a 32-bit accumulator (f * 2^32 / Fs).\n"
        " * PM_DEL_Q16: one period in samples, Q16, clamped to 4..1500 samples\n"
        " * (about MIDI 22 and below sit on the 1500-sample clamp). */\n"
        "#pragma once\n"
        "static const uint32_t PM_INC[128] = {\n"
        + rows(incs, 4, "0x{0:08X}u")
        + "\n};\n"
        "static const uint32_t PM_DEL_Q16[128] = {\n"
        + rows(dels, 4, "{0}u")
        + "\n};\n"
    )
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
